#!/usr/bin/env python3
"""Generate src/unicode_tables.rs from this interpreter's own str methods.

The Rust port has to answer every "is this a digit / a space / wide?"
question exactly the way the Python release did, so rather than trusting a
second Unicode implementation to agree, the tables are read straight out of
CPython: whatever `str.isspace`, `unicodedata.east_asian_width` and friends
say here is what the binary will say.

    python3 scripts/gen_unicode_tables.py > src/unicode_tables.rs
"""

from __future__ import annotations

import sys
import unicodedata

MAX = sys.maxunicode + 1


def chars():
    for code in range(MAX):
        if 0xD800 <= code <= 0xDFFF:
            continue
        yield code, chr(code)


def ranges(predicate):
    out = []
    start = None
    previous = None
    for code, char in chars():
        if predicate(char):
            if start is None:
                start = code
            elif previous is not None and code != previous + 1:
                out.append((start, previous))
                start = code
            previous = code
        elif start is not None:
            out.append((start, previous))
            start = None
            previous = None
    if start is not None:
        out.append((start, previous))
    return out


def emit_ranges(name, predicate):
    found = ranges(predicate)
    print("pub static %s: &[(u32, u32)] = &[" % name)
    for low, high in found:
        print("    (0x%X, 0x%X)," % (low, high))
    print("];")
    print()


def rust_str(text):
    return '"' + "".join("\\u{%X}" % ord(c) for c in text) + '"'


def emit_mapping(name, function):
    print("pub static %s: &[(u32, &str)] = &[" % name)
    for code, char in chars():
        mapped = function(char)
        if mapped != char:
            print("    (0x%X, %s)," % (code, rust_str(mapped)))
    print("];")
    print()


# Word_Break MidLetter, MidNumLet and Single_Quote, which unicodedata does not
# expose; together with the categories below they make Case_Ignorable, which
# CPython's lower() consults for the final sigma.
WORD_BREAK_IGNORABLE = {
    0x0027, 0x002E, 0x003A, 0x00B7, 0x0387, 0x055F, 0x05F4, 0x2018, 0x2019,
    0x2024, 0x2027, 0xFE13, 0xFE52, 0xFE55, 0xFF07, 0xFF0E, 0xFF1A,
}


def case_ignorable(char):
    return (unicodedata.category(char) in ("Mn", "Me", "Cf", "Lm", "Sk")
            or ord(char) in WORD_BREAK_IGNORABLE)


def decimal_value(char):
    return unicodedata.decimal(char, -1)


def main():
    print("// Generated by scripts/gen_unicode_tables.py from Python %s (Unicode %s)."
          % (sys.version.split()[0], unicodedata.unidata_version))
    print("// Do not edit by hand.")
    print()
    print("#![allow(clippy::all)]")
    print()
    emit_ranges("SPACE", str.isspace)
    emit_ranges("DIGIT", str.isdigit)
    emit_ranges("DECIMAL", str.isdecimal)
    emit_ranges("ALPHA", str.isalpha)
    emit_ranges("ALNUM", str.isalnum)
    emit_ranges("LOWER", str.islower)
    emit_ranges("UPPER", str.isupper)
    emit_ranges("TITLE", str.istitle)
    emit_ranges("PRINTABLE", str.isprintable)
    emit_ranges("COMBINING", lambda c: unicodedata.combining(c) != 0)
    emit_ranges("WIDE", lambda c: unicodedata.east_asian_width(c) in ("W", "F"))
    emit_ranges("CASE_IGNORABLE", case_ignorable)
    # The decimal value of every Nd digit, as ranges sharing one zero.
    print("pub static DECIMAL_ZERO: &[(u32, u32)] = &[")
    for low, high in ranges(str.isdecimal):
        # Decimal digits come in runs of ten counted up from zero.
        code = low
        while code <= high:
            zero = code - decimal_value(chr(code))
            print("    (0x%X, 0x%X)," % (code, zero))
            code += 1
    print("];")
    print()
    emit_mapping("LOWER_MAP", str.lower)
    emit_mapping("CASEFOLD_MAP", str.casefold)


if __name__ == "__main__":
    main()
